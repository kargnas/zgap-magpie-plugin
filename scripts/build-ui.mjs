import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from "node:fs"

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8")
const write = (path, value) => writeFileSync(new URL(`../${path}`, import.meta.url), value)
const resources = Object.fromEntries(readdirSync(new URL("../locales/", import.meta.url)).filter((file) => file.endsWith(".json")).sort().map((file) => [file.slice(0, -5), { translation: JSON.parse(read(`locales/${file}`)) }]))
const messages = (key) => Object.fromEntries(Object.entries(resources).map(([lang, value]) => [lang, value.translation[key]]))
const pkg = JSON.parse(read("package.json"))
pkg.magpie.icon = `data:image/svg+xml;base64,${Buffer.from(read("ui/icon.svg")).toString("base64")}`
pkg.magpie.summary = messages("summary")
pkg.magpie.page = { title: "ZGAP", file: "ui/index.html", icon: "ui/icon.svg" }
pkg.magpie.panels = [{ slot: "settings", file: "ui/panel.html", title: resources.en.translation.panelTitle, titles: messages("panelTitle") }]
pkg.magpie.actions = ["provider", "agent"].map((menu) => ({ id: `${menu}-setup`, menu, title: resources.en.translation.menuTitle, titles: messages("menuTitle") }))
write("package.json", `${JSON.stringify(pkg, null, 2)}\n`)
// The page sandbox cannot fetch translations or CDN scripts, so all assets ship with the plugin.
write("ui/messages.js", `/* Generated by npm run build:ui from locales/*.json. */\nglobalThis.zgapMessages = ${JSON.stringify(resources)}\n`)
mkdirSync(new URL("../ui/vendor/", import.meta.url), { recursive: true })
for (const [source, destination] of [["dist/umd/i18next.min.js", "i18next.min.js"], ["LICENSE", "i18next.LICENSE"]]) {
  copyFileSync(new URL(`../node_modules/i18next/${source}`, import.meta.url), new URL(`../ui/vendor/${destination}`, import.meta.url))
}
